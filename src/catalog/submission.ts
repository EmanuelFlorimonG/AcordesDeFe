import { parseSongDraft, type SongDraft } from './songDraft';
import { validateSongDraft, type SongValidationIssue, type SongValidationOptions } from './validateSongDraft';

/**
 * A submission is a proposal: a new song, or a correction of a published one.
 * It never changes the catalog by itself. Only an approval, done by the
 * backend for an authorized reviewer, publishes it (see the migration's
 * approve_submission function).
 */

export type SongSubmissionType = 'create' | 'update';
export type SongSubmissionStatus = 'pending' | 'changes_requested' | 'rejected' | 'approved';

export const SUBMISSION_STATUS_LABELS: Record<SongSubmissionStatus, string> = {
  pending: 'En revisión',
  changes_requested: 'Cambios solicitados',
  rejected: 'No aprobada',
  approved: 'Aprobada',
};

export const SUBMISSION_PAYLOAD_SCHEMA_VERSION = 1;
export const MAX_CONTRIBUTOR_NAME_LENGTH = 80;
export const MAX_CONTRIBUTOR_EMAIL_LENGTH = 254;
/** A whole proposal, as JSON; the database enforces the same limit */
export const MAX_SUBMISSION_BYTES = 65_536;

/**
 * Who sent it: both optional, and nothing else is ever asked. The email is
 * only for the review team to reply; it is never published, never returned by
 * the public status check, and never part of the song.
 */
export interface SongSubmissionContributor {
  name: string | null;
  email: string | null;
}

/** What a visitor sends. The song travels whole, exactly as written. */
export interface SongSubmissionPayload {
  schemaVersion: typeof SUBMISSION_PAYLOAD_SCHEMA_VERSION;
  type: SongSubmissionType;
  /** The published song a correction is for; null for a new song */
  targetSongId: string | null;
  song: SongDraft;
  contributor: SongSubmissionContributor;
  /**
   * Makes sending safe to retry. Generated once by the browser before the
   * first attempt and reused on every retry of the same proposal: if the
   * first attempt reached the database but its answer was lost, the retry
   * gets the same tracking code back instead of creating a second proposal.
   */
  requestId?: string;
  /**
   * The secret for editing this proposal later, generated by the browser
   * (64 hex characters). The database stores only its SHA-256, and a retry is
   * recognised only when it carries the same token.
   */
  editToken?: string;
}

/**
 * A stored submission, as the review side sees it. Only reviewers read this
 * (through the database's policies); the public never receives it.
 */
export interface SongSubmission {
  id: string;
  type: SongSubmissionType;
  targetSongId: string | null;
  proposedSong: SongDraft;
  status: SongSubmissionStatus;
  contributorName: string | null;
  contributorEmail: string | null;
  trackingCode: string;
  /** Written by the reviewer for the contributor; public once the review is done */
  reviewNote: string | null;
  submittedAt: string;
  reviewedAt: string | null;
  createdAt: string;
  updatedAt: string;
}

/**
 * What the sender gets back, once. The tracking code checks the status; the
 * edit token is a separate secret kept for a later "edit my submission"
 * without an account. The database only stores a hash of the token.
 */
export interface SubmissionReceipt {
  trackingCode: string;
  editToken: string;
}

/** The only view of a submission anyone can get with a tracking code. */
export interface PublicSubmissionStatus {
  trackingCode: string;
  type: SongSubmissionType;
  title: string;
  status: SongSubmissionStatus;
  /** Only once reviewed; never while pending */
  reviewNote: string | null;
  submittedAt: string;
  reviewedAt: string | null;
}

/** The safe projection, field by field: nothing is copied that isn't listed here. */
export function toPublicStatus(submission: SongSubmission): PublicSubmissionStatus {
  return {
    trackingCode: submission.trackingCode,
    type: submission.type,
    title: submission.proposedSong.title,
    status: submission.status,
    reviewNote: submission.status === 'pending' ? null : submission.reviewNote,
    submittedAt: submission.submittedAt,
    reviewedAt: submission.reviewedAt,
  };
}

export function buildSubmissionPayload(
  song: SongDraft,
  {
    type,
    targetSongId = null,
    contributor = { name: null, email: null },
    attempt,
  }: {
    type: SongSubmissionType;
    targetSongId?: string | null;
    contributor?: Partial<SongSubmissionContributor>;
    /** The retry identity of this proposal (see SubmissionAttempt) */
    attempt?: SubmissionAttempt;
  }
): SongSubmissionPayload {
  const clean = (value: string | null | undefined) => (value && value.trim() ? value.trim() : null);
  return {
    schemaVersion: SUBMISSION_PAYLOAD_SCHEMA_VERSION,
    type,
    targetSongId: type === 'update' ? targetSongId : null,
    song,
    contributor: { name: clean(contributor.name), email: clean(contributor.email)?.toLowerCase() ?? null },
    ...(attempt ? { requestId: attempt.requestId, editToken: attempt.editToken } : {}),
  };
}

/** One proposal's identity across retries: created before the first attempt, kept until it succeeds. */
export interface SubmissionAttempt {
  requestId: string;
  editToken: string;
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const TOKEN = /^[0-9a-f]{64}$/;

export function createSubmissionAttempt(random: (length: number) => Uint8Array = (length) => crypto.getRandomValues(new Uint8Array(length))): SubmissionAttempt {
  const hex = (bytes: Uint8Array) => [...bytes].map((byte) => byte.toString(16).padStart(2, '0')).join('');
  const id = random(16);
  // RFC 4122 version 4 layout.
  id[6] = (id[6] & 0x0f) | 0x40;
  id[8] = (id[8] & 0x3f) | 0x80;
  const h = hex(id);
  return {
    requestId: `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`,
    editToken: hex(random(32)),
  };
}

export function isSubmissionAttempt(value: unknown): value is SubmissionAttempt {
  if (typeof value !== 'object' || value === null) return false;
  const entry = value as Record<string, unknown>;
  return typeof entry.requestId === 'string' && UUID.test(entry.requestId) && typeof entry.editToken === 'string' && TOKEN.test(entry.editToken);
}

export type SubmissionIssueCode =
  | 'type-invalid'
  | 'target-required'
  | 'target-unknown'
  | 'contributor-name-too-long'
  | 'contributor-email-invalid'
  | 'too-large'
  | 'song-invalid';

export interface SubmissionValidationResult {
  ok: boolean;
  errors: Array<{ code: SubmissionIssueCode; message: string }>;
  /** The song's own check, errors and warnings, for the editor to show in place */
  song: { errors: SongValidationIssue[]; warnings: SongValidationIssue[] };
}

// Deliberately simple: something@something.tld. The real check is the reply.
const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;

/**
 * Everything checked before sending. The database checks the same limits
 * again: this is for the person writing, not the security boundary.
 */
export function validateSubmissionPayload(
  payload: SongSubmissionPayload,
  options: SongValidationOptions & { publishedSongIds?: ReadonlySet<string> } = {}
): SubmissionValidationResult {
  const errors: SubmissionValidationResult['errors'] = [];
  if (payload.type !== 'create' && payload.type !== 'update') errors.push({ code: 'type-invalid', message: 'Tipo de propuesta desconocido.' });
  if (payload.type === 'update') {
    if (!payload.targetSongId) errors.push({ code: 'target-required', message: 'Falta la canción que se corrige.' });
    else if (options.publishedSongIds && !options.publishedSongIds.has(payload.targetSongId)) {
      errors.push({ code: 'target-unknown', message: 'La canción que se corrige no está en el catálogo.' });
    }
  }
  const { name, email } = payload.contributor;
  if (name && name.length > MAX_CONTRIBUTOR_NAME_LENGTH) {
    errors.push({ code: 'contributor-name-too-long', message: `El nombre no puede pasar de ${MAX_CONTRIBUTOR_NAME_LENGTH} caracteres.` });
  }
  if (email && (email.length > MAX_CONTRIBUTOR_EMAIL_LENGTH || !EMAIL.test(email))) {
    errors.push({ code: 'contributor-email-invalid', message: 'El correo no parece válido.' });
  }
  if (new TextEncoder().encode(JSON.stringify(payload)).length > MAX_SUBMISSION_BYTES) {
    errors.push({ code: 'too-large', message: 'La propuesta es demasiado grande.' });
  }
  const song = validateSongDraft(payload.song, options);
  if (!song.ok) errors.push({ code: 'song-invalid', message: 'La canción tiene errores que corregir.' });
  return { ok: errors.length === 0, errors, song: { errors: song.errors, warnings: song.warnings } };
}

/** A payload from untrusted JSON, or null. */
export function parseSubmissionPayload(value: unknown): SongSubmissionPayload | null {
  if (typeof value !== 'object' || value === null) return null;
  const entry = value as Record<string, unknown>;
  if (entry.schemaVersion !== SUBMISSION_PAYLOAD_SCHEMA_VERSION) return null;
  if (entry.type !== 'create' && entry.type !== 'update') return null;
  const song = parseSongDraft(entry.song);
  if (!song) return null;
  const contributor = (typeof entry.contributor === 'object' && entry.contributor !== null ? entry.contributor : {}) as Record<string, unknown>;
  return {
    schemaVersion: SUBMISSION_PAYLOAD_SCHEMA_VERSION,
    type: entry.type,
    targetSongId: typeof entry.targetSongId === 'string' ? entry.targetSongId : null,
    song,
    contributor: {
      name: typeof contributor.name === 'string' ? contributor.name : null,
      email: typeof contributor.email === 'string' ? contributor.email : null,
    },
  };
}

/**
 * A proposal read back by its author to correct it (tracking code + edit
 * token). Only the author's own content and the reviewer's note: never the
 * contact data.
 */
export interface SubmissionForEdit {
  trackingCode: string;
  type: SongSubmissionType;
  status: SongSubmissionStatus;
  reviewNote: string | null;
  /** Null when what is stored can't be read as a song */
  song: SongDraft | null;
}

export interface ResubmitInput {
  trackingCode: string;
  editToken: string;
  song: SongDraft;
}

export interface ResubmitReceipt {
  trackingCode: string;
  status: SongSubmissionStatus;
}
